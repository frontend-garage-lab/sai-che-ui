function forkDiff(tag, api) {
  const up = baseline.elements[tag];
  if (!up) return { kind: 'new', changes: [] };
  const changes = [];
  for (const [name, attr] of Object.entries(api.attrs)) {
    const before = up.attrs[name];
    if (!before) {
      changes.push(`new attribute \`${name}\`${attr.values ? ` (${attr.values.map(v => `'${v}'`).join(' | ')})` : ''}`);
    } else if (before.values && attr.values) {
      const added = attr.values.filter(v => !before.values.includes(v));
      const removed = before.values.filter(v => !attr.values.includes(v));
      if (added.length) changes.push(`\`${name}\` accepts new values: ${added.map(v => `'${v}'`).join(', ')}`);
      if (removed.length) changes.push(`\`${name}\` no longer accepts: ${removed.map(v => `'${v}'`).join(', ')}`);
    }
  }
  for (const name of Object.keys(up.attrs)) {
    if (!api.attrs[name]) changes.push(`attribute \`${name}\` was removed`);
  }
  const diffList = (label, now, before) => {
    for (const n of now) if (!before.includes(n)) changes.push(`new ${label} \`${n || '(default)'}\``);
    for (const n of before) if (!now.includes(n)) changes.push(`${label} \`${n || '(default)'}\` was removed`);
  };
  diffList(
    'event',
    api.events.map(e => e.name),
    up.events
  );
  diffList(
    'slot',
    api.slots.map(s => s.name),
    up.slots
  );
  diffList(
    'CSS part',
    api.parts.map(p => p.name),
    up.parts
  );
  diffList(
    'CSS custom property',
    api.cssProps.map(c => c.name),
    up.cssProps
  );
  return { kind: changes.length ? 'modified' : 'unchanged', changes };
}

