const themeCss = fs.readFileSync(path.join(root, 'dist/themes/light.css'), 'utf8');
const tokens = {};
for (const match of themeCss.matchAll(/^\s*(--sl-[a-z0-9-]+)\s*:\s*([^;]+);/gm)) tokens[match[1]] = match[2].trim();
const darkCss = fs.readFileSync(path.join(root, 'dist/themes/dark.css'), 'utf8');
