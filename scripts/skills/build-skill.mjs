function frontMatter(md) {
  const match = md.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return { body: md, title: '', description: '' };
  const fm = match[1];
  return {
    body: md.slice(match[0].length),
    title: (fm.match(/^\s*title:\s*(.+)$/m) || [])[1]?.trim() || '',
    description: (fm.match(/^\s*description:\s*(.+)$/m) || [])[1]?.trim() || ''
  };
}

/**
 * Turns a docs page into a reference: drops React snippets, keeps one Angular snippet (plus those that follow an
 * example needing JavaScript), resolves the build placeholders and rewrites links so they stay inside the skill.
 */
function processDoc(md, { linkBase = '' } = {}) {
  let text = md
    .replace(/\{%\s*(end)?raw\s*%\}\n?/g, '')
    .replace(/%NPMDIR%/g, 'dist')
    .replace(/%CDNDIR%/g, 'cdn')
    .replace(/%VERSION%/g, pkg.version);

  const lines = text.split('\n');
  const out = [];
  let angularKept = false;
  let lastHtmlNeedsScript = false;
  for (let i = 0; i < lines.length; i++) {
    const fence = lines[i].match(/^```(\S*)\s*$/);
    if (!fence || !fence[1]) {
      out.push(lines[i]);
      continue;
    }
    const lang = fence[1];
    const block = [lines[i]];
    while (++i < lines.length && !/^```\s*$/.test(lines[i])) block.push(lines[i]);
    block.push('```');
    const content = block.slice(1, -1).join('\n');

    if (lang.startsWith('jsx')) continue;
    if (lang === 'ts:angular') {
      if (angularKept && !lastHtmlNeedsScript) continue;
      angularKept = true;
      block[0] = '```ts';
    } else if (lang.startsWith('html')) {
      lastHtmlNeedsScript = /<script/.test(content);
      block[0] = '```html';
    }
    out.push(...block);
  }
  text = out.join('\n');

  text = text.replace(/^:::(tip|warning|danger)\s*\n([\s\S]*?)\n:::\s*$/gm, (_m, kind, inner) => {
    const label = { tip: 'Tip', warning: 'Warning', danger: 'Important' }[kind];
    return inner
      .split('\n')
      .map((l, idx) => `> ${idx === 0 ? `**${label}:** ` : ''}${l}`)
      .join('\n');
  });
  return (
    rewriteLinks(text, linkBase)
      .replace(/\n{3,}/g, '\n\n')
      .trim() + '\n'
  );
}

/**
 * Rewrites docs-site links so they stay inside the skill. `base` is the path from the file being written to the
 * components folder ('' for files inside it, 'components/' for files next to it).
 */
function rewriteLinks(text, base) {
  const angular = base === '' ? '../angular.md' : 'angular.md';
  return text
    .replace(/\]\(\/components\/([a-z-]+)\/?(#[^)]*)?\)/g, (_m, name, hash) => `](${base}${name}.md${hash || ''})`)
    .replace(/\]\(\/frameworks\/angular\/?(#[^)]*)?\)/g, (_m, hash) => `](${angular}${hash || ''})`)
    .replace(/\[([^\]]+)\]\(\/[^)]*\)/g, '$1');
}

// ---------------------------------------------------------------------------------------------------------------
// Markdown helpers
// ---------------------------------------------------------------------------------------------------------------

const cell = text =>
  String(text ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ')
    .trim() || '—';
const code = text => (text ? `\`${String(text).replace(/\|/g, '\\|')}\`` : '—');
const table = (headers, rows) =>
  rows.length
    ? [
        `| ${headers.join(' | ')} |`,
        `| ${headers.map(() => '---').join(' | ')} |`,
        ...rows.map(r => `| ${r.join(' | ')} |`)
      ].join('\n') + '\n'
    : '';
const importPath = api => `${PKG}/dist/${api.module.replace(/^\//, '')}`;
const firstSentence = text => (text.match(/^(.+?[.!?])(\s|$)/) || [null, text])[1];

function typeCell(attr) {
  if (attr.values) {
    const values = attr.values.map(v => (v === '' ? "`''`" : `\`${v}\``)).join(', ');
    return attr.open ? `${values} or any string` : values;
  }
  return code(attr.type);
}

