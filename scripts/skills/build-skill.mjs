function componentReference(tag) {
  const api = apis[tag];
  const name = tag.slice(PREFIX.length);
  const docPath = path.join(root, `docs/pages/components/${name}.md`);
  const doc = fs.existsSync(docPath) ? frontMatter(fs.readFileSync(docPath, 'utf8')) : null;
  const diff = diffs[tag];
  const title = doc?.title || name;
  const lines = [];

  lines.push(
    generatedNote(`dist/custom-elements.json${doc ? ` and docs/pages/components/${name}.md` : ''}`) +
      `# \`<${tag}>\` — ${title}\n`
  );
  if (diff.kind === 'new') {
    lines.push(
      '> **Only in Saipem DS.** This component does not exist in upstream Shoelace or Web Awesome: use only the API below.\n'
    );
  } else if (diff.kind === 'modified') {
    lines.push(
      `> **Customized in Saipem DS.** It differs from upstream Shoelace: ${diff.changes.join('; ')}. Use only the API below.\n`
    );
  }
  lines.push(api.summary + '\n');
  const meta = [];
  if (api.status) meta.push(`**Status:** ${api.status}`);
  if (api.since) meta.push(`**Since:** ${api.since}`);
  if (meta.length) lines.push(meta.join(' · ') + '\n');
  lines.push(`**Import:** \`import '${importPath(api)}';\`\n`);
  if (api.dependencies.length) {
    lines.push(
      `**Uses internally (registered automatically):** ${api.dependencies.map(d => `\`<${d}>\``).join(', ')}\n`
    );
  }

  const attrRows = Object.entries(api.attrs).map(([attrName, a]) => [
    code(attrName),
    a.prop && a.prop !== attrName ? code(a.prop) : '—',
    typeCell(a),
    a.default !== undefined ? code(a.default) : '—',
    cell(a.description)
  ]);
  if (attrRows.length) {
    lines.push('## Attributes\n');
    lines.push(
      'Every attribute is also a property (camelCase name in the second column when it differs). Boolean attributes are ' +
        'on when present: never write `="false"`, remove the attribute or bind the property instead.\n'
    );
    lines.push(table(['Attribute', 'Property', 'Type / allowed values', 'Default', 'Description'], attrRows));
  }

  const propOnlyRows = Object.entries(api.props)
    .filter(([propName, p]) => !p.attr && p.description && !Object.values(api.attrs).some(a => a.prop === propName))
    .map(([propName, p]) => [code(propName), code(p.type), p.readonly ? 'read-only' : '', cell(p.description)]);
  if (propOnlyRows.length) {
    lines.push('## Properties without an attribute\n');
    lines.push(
      'These can only be set from JavaScript: `element.prop = value`, `[prop]="value"` in Angular, `.prop=${value}` in Lit. ' +
        'Writing them as HTML attributes does nothing.\n'
    );
    lines.push(table(['Property', 'Type', 'Notes', 'Description'], propOnlyRows));
  }

  if (api.events.length) {
    lines.push('## Events\n');
    lines.push(
      'Listen with `addEventListener`, `(event-name)` in Angular or `@event-name` in Lit. Data is on `event.detail`.\n'
    );
    lines.push(
      table(
        ['Event', '`event.detail`', 'Description'],
        api.events.map(e => [code(e.name), code(e.detail), cell(e.description)])
      )
    );
  }

  if (api.methods.length) {
    lines.push('## Methods\n');
    lines.push(
      table(
        ['Method', 'Description'],
        api.methods.map(m => [
          code(
            `${m.name}(${m.params.map(p => `${p.name}${p.optional ? '?' : ''}${p.type ? `: ${p.type}` : ''}`).join(', ')})`
          ),
          cell(m.description)
        ])
      )
    );
  }

  if (api.slots.length) {
    lines.push('## Slots\n');
    lines.push(
      table(
        ['Slot', 'Description'],
        api.slots.map(s => [s.name ? code(s.name) : '(default)', cell(s.description)])
      )
    );
  }

  if (api.parts.length) {
    lines.push('## CSS parts\n');
    lines.push(
      'Parts exist for fine adjustments. Do not use them to change colours, borders or fonts: a missing look is a missing ' +
        'variant of the DS.\n'
    );
    lines.push(
      table(
        ['Part', 'Description'],
        api.parts.map(p => [code(p.name), cell(p.description)])
      )
    );
  }

  if (api.cssProps.length) {
    lines.push('## CSS custom properties\n');
    lines.push(
      table(
        ['Property', 'Default', 'Description'],
        api.cssProps.map(c => [code(c.name), c.default ? code(c.default) : '—', cell(c.description)])
      )
    );
  }

  if (doc) {
    lines.push('## Documentation and examples\n');
    lines.push(processDoc(doc.body));
  }

  return lines.join('\n').replace(/\n{3,}/g, '\n\n');
}

