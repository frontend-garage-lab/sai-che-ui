//
// This script generates the Saipem semantic colour ramps and writes them into the theme
// files, in place, between the @palettes markers. It also checks that every role's resting
// fill clears WCAG AA against its own ink token and exits non-zero if one doesn't.
//
// Run it with `npm run palettes`. It is deliberately NOT part of `npm run build`: it writes
// into src/, which build.js watches, so calling it from the build would loop.
//
import chalk from 'chalk';
import fs from 'fs';
import prettier from 'prettier';
import { BRAND, CONTRAST_FLOOR, CONTRAST_TARGET, DARK, LIGHT, ROLES, STEPS } from './palettes.config.js';

const START = '/* @palettes:start — generated by scripts/make-palettes.js, do not edit by hand */';
const END = '/* @palettes:end */';

//
// Colour maths. HSL in, sRGB out, plus WCAG 2.1 relative luminance and contrast.
//
function hslToRgb(h, s, l) {
  const sat = s / 100;
  const lig = l / 100;
  const c = (1 - Math.abs(2 * lig - 1)) * sat;
  const hp = (((h % 360) + 360) % 360) / 60;
  const x = c * (1 - Math.abs((hp % 2) - 1));
  const [r, g, b] = [
    [c, x, 0],
    [x, c, 0],
    [0, c, x],
    [0, x, c],
    [x, 0, c],
    [c, 0, x]
  ][Math.floor(hp) % 6];
  const m = lig - c / 2;
  return [r + m, g + m, b + m];
}

function luminance([r, g, b]) {
  const f = v => (v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4));
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}

function contrast(a, b) {
  const [la, lb] = [luminance(a), luminance(b)];
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}

const hsl = (h, s, l) => hslToRgb(h, s, l);
const hex = ([r, g, b]) =>
  '#' +
  [r, g, b]
    .map(v =>
      Math.round(Math.min(1, Math.max(0, v)) * 255)
        .toString(16)
        .padStart(2, '0')
    )
    .join('')
    .toUpperCase();

// Trim trailing zeroes so we emit "45%" rather than "45.0%", matching the existing files.
const num = v => String(Math.round(v * 10) / 10);
const css = (h, s, l) => `hsl(${num(h)} ${num(s)}% ${num(l)}%)`;

// Lightness at which `ink` first clears the contrast target against a fill of this hue.
// `direction` is 'darker' for light themes (fills get darker until white text works) and
// 'lighter' for dark themes (fills get lighter until near-black text works).
function solveLightness(hue, saturation, ink, direction) {
  let lo = 5;
  let hi = 95;
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    const ok = contrast(ink, hsl(hue, saturation, mid)) >= CONTRAST_TARGET;
    if (direction === 'darker') {
      if (ok) lo = mid;
      else hi = mid;
    } else if (ok) hi = mid;
    else lo = mid;
  }
  return Math.round((direction === 'darker' ? lo : hi) * 10) / 10;
}

function interpolate(i, x0, y0, x1, y1) {
  return y0 + ((y1 - y0) * (i - x0)) / (x1 - x0);
}

//
// Ramp builders.
//
function lightRamp(role, ink) {
  const { hue, saturation } = ROLES[role];
  const spec = LIGHT.anchors[role];
  const anchors = { 0: LIGHT.endpoints.first, [STEPS.length - 1]: LIGHT.endpoints.last };

  for (const [step, value] of Object.entries(spec)) {
    const i = STEPS.indexOf(Number(step));
    anchors[i] = value === 'contrast' ? solveLightness(hue, saturation, ink, 'darker') : value;
  }

  const keys = Object.keys(anchors)
    .map(Number)
    .sort((a, b) => a - b);

  return STEPS.map((step, i) => {
    let lightness = anchors[i];
    if (lightness === undefined) {
      const next = keys.find(k => k > i);
      const prev = [...keys].reverse().find(k => k < i);
      lightness = interpolate(i, prev, anchors[prev], next, anchors[next]);
    }
    const pinned = LIGHT.saturationAnchors?.[role]?.[step];
    return { step, hue, saturation: pinned ?? saturation * LIGHT.saturation[step], lightness };
  });
}

function darkRamp(role, ink) {
  const { hue, saturation } = ROLES[role];
  const spec = DARK.anchors[role];

  return STEPS.map((step, i) => {
    let lightness = spec[step] ?? DARK.lightness[i];
    if (spec[step] === 'contrast') lightness = solveLightness(hue, saturation, ink, 'lighter');
    const pinned = DARK.saturationAnchors?.[role]?.[step];
    return { step, hue, saturation: pinned ?? saturation * DARK.saturation[step], lightness };
  });
}

function neutralRamp(theme) {
  const { hue, steps } = theme.neutral;
  return STEPS.map(step => {
    const [saturation, lightness] = steps[step];
    return { step, hue, saturation, lightness };
  });
}

//
// CSS emitter.
//
function render(theme, name) {
  const ink = theme.ink;
  const ramps = {};
  const base = hsl(...theme.oneOffs[0]);
  for (const role of Object.keys(ROLES)) {
    ramps[role] = name === 'light' ? lightRamp(role, base) : darkRamp(role, base);
  }
  ramps.neutral = neutralRamp(theme);

  const lines = [];
  const label = {
    primary: `Primary — the Saipem petrol, ${BRAND.petrol.hex}`,
    accent: `Accent — the Saipem orange, ${BRAND.orange.hex}`,
    success: 'Success',
    warning: 'Warning',
    danger: 'Danger',
    neutral: 'Neutral — near-neutral greys with a faint cool cast'
  };

  for (const [role, ramp] of Object.entries(ramps)) {
    lines.push(`  /* ${label[role]} */`);
    for (const { step, hue, saturation, lightness } of ramp) {
      lines.push(`  --sl-color-${role}-${step}: ${css(hue, saturation, lightness)};`);
    }
    lines.push('');
  }

  lines.push('  /* Neutral one-offs */');
  for (const [step, value] of Object.entries(theme.oneOffs)) {
    lines.push(`  --sl-color-neutral-${step}: ${css(...value)};`);
  }
  lines.push('');

  lines.push('  /*');
  lines.push("   * Ink — the text colour that belongs on a role's resting fill.");
  lines.push('   * Always pair a fill with its own ink token; never hardcode neutral-0.');
  lines.push('   */');
  for (const [role, value] of Object.entries(ink)) {
    lines.push(`  --sl-color-${role}-contrast: ${value};`);
  }

  return { css: lines.join('\n'), ramps };
}

//
// Contrast report. This is the safety net for the whole colour system: the axe
// color-contrast rule can't see shadow-DOM-styled slotted text, so it will not catch a
// regression here.
//
function audit(name, ramps, theme) {
  const ink = theme.ink;
  const base = hsl(...theme.oneOffs[0]);
  const resolveInk = role => {
    const token = ink[role];
    if (token.includes('neutral-0')) return base;
    // The only other ink in use is primary-950.
    const step = ramps.primary.find(s => s.step === 950);
    return hsl(step.hue, step.saturation, step.lightness);
  };

  const rows = [];
  let failed = false;

  for (const role of Object.keys(ramps)) {
    if (role === 'neutral') continue;
    const fillStep = role === 'accent' && name === 'light' ? 500 : 600;
    const fill = ramps[role].find(s => s.step === fillStep);
    const fillRgb = hsl(fill.hue, fill.saturation, fill.lightness);
    const ratio = contrast(resolveInk(role), fillRgb);
    const ok = ratio >= CONTRAST_FLOOR;
    if (!ok) failed = true;
    rows.push(
      `  ${ok ? chalk.green('PASS') : chalk.red('FAIL')} ${role.padEnd(8)} ${String(fillStep).padEnd(4)} ` +
        `${hex(fillRgb)}  ink on fill ${ratio.toFixed(2)}`
    );
  }

  // Tint pattern: the 800 text that <sl-tag> puts on a 50 background.
  for (const role of Object.keys(ramps)) {
    if (role === 'neutral') continue;
    const bg = ramps[role].find(s => s.step === 50);
    const fg = ramps[role].find(s => s.step === 800);
    const ratio = contrast(hsl(fg.hue, fg.saturation, fg.lightness), hsl(bg.hue, bg.saturation, bg.lightness));
    const ok = ratio >= CONTRAST_FLOOR;
    if (!ok) failed = true;
    rows.push(
      `  ${ok ? chalk.green('PASS') : chalk.red('FAIL')} ${role.padEnd(8)} tint  800 on 50    ${ratio.toFixed(2)}`
    );
  }

  // Neutral pairings: body text, placeholders, help text and control borders.
  const neutral = step => {
    if (step === 0) return base;
    const s = ramps.neutral.find(n => n.step === step);
    return hsl(s.hue, s.saturation, s.lightness);
  };
  for (const [fg, bg, floor, label] of theme.audit) {
    const ratio = contrast(neutral(fg), neutral(bg));
    const ok = ratio >= floor;
    if (!ok) failed = true;
    rows.push(
      `  ${ok ? chalk.green('PASS') : chalk.red('FAIL')} neutral  ${`${fg} on ${bg}`.padEnd(10)} ` +
        `${ratio.toFixed(2).padEnd(5)} (≥${floor}) ${label}`
    );
  }

  console.log(chalk.cyan(`\n${name} theme — contrast audit (floor ${CONTRAST_FLOOR}:1)`));
  console.log(rows.join('\n'));
  return failed;
}

//
// Write the generated block back into each theme file.
//
async function write(file, block) {
  const source = fs.readFileSync(file, 'utf8');
  if (!source.includes(START) || !source.includes(END)) {
    throw new Error(`${file} is missing the @palettes markers`);
  }
  const before = source.slice(0, source.indexOf(START));
  const after = source.slice(source.indexOf(END) + END.length);
  // Resolve the repo's own Prettier config so the generated file matches what
  // `npm run prettier:check` expects; otherwise the generator and the check disagree.
  const options = (await prettier.resolveConfig(file)) ?? {};
  const next = await prettier.format(`${before}${START}\n${block}\n  ${END}${after}`, {
    ...options,
    parser: 'css'
  });
  fs.writeFileSync(file, next, 'utf8');
  console.log(`  ${chalk.green('✓')} ${file}`);
}

let failed = false;
console.log(chalk.cyan('Generating Saipem palettes'));

for (const [name, theme] of [
  ['light', LIGHT],
  ['dark', DARK]
]) {
  const { css: block, ramps } = render(theme, name);
  await write(`src/themes/${name}.css`, block);
  if (audit(name, ramps, theme)) failed = true;
}

if (failed) {
  console.error(
    chalk.red('\nContrast audit failed — a pairing is below its floor. Adjust scripts/palettes.config.js.')
  );
  process.exit(1);
}

console.log(chalk.green('\nContrast audit passed.'));
